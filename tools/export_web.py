"""Level data for the HTML player (web/), and test data for its engine.

Usage:
  export_web.py                     writes web/episodes.js from designs/episodes.json: one pack
                                    per episode
  export_web.py --golden OUT.json   light from sim.py for every level: the stored solution, the
                                    empty board, and random placements;
                                    web/test/engine_test.js checks engine.js against it

The page is opened from disk, where it can't fetch JSON, so the levels are a script that sets
LASER_PUZZLE_EPISODES. Pieces are compact arrays: board [type, x, y, dir, colour] and toolbox
[type, colour, x, y, dir], the last three being the stored solution.
"""
import json
import os
import random
import sys

import sim

ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..')


def episodes():
    """[(id, name, title, levels)], one per episode of designs/episodes.json."""
    data = json.load(open(os.path.join(ROOT, 'designs', 'episodes.json')))
    return [(f'ep{k}', f'Episode {k}', title, [lv for lv in data['levels'] if lv['episode'] == k])
            for k, title in enumerate(data['episodes'], 1)]


def compact(level):
    T = sim.TYPE_IDS
    lv = dict(id=level.get('id'), t=level.get('title') or '', x=level.get('text') or '',
              b=[[T[p['type']], p['x'], p['y'], p['dir'], p['color']] for p in level['board']],
              m=[[T[t['type']], t['color'], s['x'], s['y'], s['dir']]
                 for t, s in zip(level['toolbox'], level['solution'])])
    return lv


def write_levels(out):
    data = [dict(id=i, name=n, desc=d, levels=[compact(lv) for lv in levels])
            for i, n, d, levels in episodes()]
    with open(out, 'w') as fh:
        fh.write('// Generated by tools/export_web.py; do not edit.\n')
        fh.write('var LASER_PUZZLE_EPISODES = [\n')
        for p in data:
            fh.write(json.dumps(p, separators=(',', ':')) + ',\n')
        fh.write('];\n')
    print(f'{out}: {len(data)} episodes, {sum(len(p["levels"]) for p in data)} levels')


def light(pieces):
    b = sim.Board()
    for t, x, y, d, c in pieces:
        b.cells[y][x].type, b.cells[y][x].dir, b.cells[y][x].color = t, d, c
    rules = sim.Rules()
    sim.trace(b, rules)
    cells = ''.join(''.join(str(v) for v in c.inc + c.out) for row in b.cells for c in row)
    return cells, rules.won(b)


def write_golden(out, variants=4):
    rnd = random.Random(1)
    cases = []
    for pid, _, _, levels in episodes():
        for n, level in enumerate(levels, 1):
            lv = compact(level)
            board = lv['b']
            solved = board + [[t, x, y, d, c] for t, c, x, y, d in lv['m']]
            tries = [('solved', solved), ('empty', board)]
            used = {(p[1], p[2]) for p in board}
            free = [(x, y) for y in range(sim.N) for x in range(sim.N) if (x, y) not in used]
            for k in range(variants):
                spots = rnd.sample(free, len(lv['m']))
                tries.append((f'random{k}', board + [[t, x, y, rnd.randrange(8), c]
                                                     for (t, c, *_), (x, y) in zip(lv['m'], spots)]))
            for name, pieces in tries:
                cells, won = light(pieces)
                cases.append(dict(name=f'{pid} L{n} {name}', pieces=pieces, cells=cells, won=won))
    json.dump(cases, open(out, 'w'))
    print(f'{out}: {len(cases)} cases')


if __name__ == '__main__':
    if len(sys.argv) > 2 and sys.argv[1] == '--golden':
        write_golden(sys.argv[2])
    else:
        write_levels(os.path.join(ROOT, 'web', 'episodes.js'))
